    public function run(): void
    {
        $sort = 0;
        foreach ($this->catalog() as $direction) {
            $sort += 10;
            /** @var list<array<string, mixed>> $children */
            $children = $direction['children'];
            unset($direction['children']);

            $parent = $this->upsert($direction + ['sort_order' => $sort, 'parent_id' => null]);

            $childSort = 0;
            foreach ($children as $child) {
                $childSort += 10;
                $this->upsert($child + ['sort_order' => $childSort, 'parent_id' => $parent->id]);
            }
        }
    }

    /**
     * @param  array<string, mixed>  $data
     */
    private function upsert(array $data): Service
    {
        /** @var string $slug */
        $slug = $data['slug'];

        return Service::query()->firstOrCreate(['slug' => $slug], $data + ['is_published' => true]);
    }

